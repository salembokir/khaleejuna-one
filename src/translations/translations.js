// Functions to manage language
function getCurrentLanguage() {
    return localStorage.getItem('khaleejuna_lang') || 'ar';
}

function applyTranslations(lang) {
    const dict = translations[lang] || translations.ar;
    
    // Set HTML dir and lang attributes
    document.documentElement.lang = lang;
    document.documentElement.dir = (lang === 'en') ? 'ltr' : 'rtl';
    
    // Translate text nodes with data-i18n
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (dict[key] !== undefined) {
            el.innerHTML = dict[key];
        }
    });
    
    // Translate placeholders with data-i18n-placeholder
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
        const key = el.getAttribute('data-i18n-placeholder');
        if (dict[key] !== undefined) {
            el.setAttribute('placeholder', dict[key]);
        }
    });
    
    // Update language toggle button label
    const langBtnText = document.querySelector('.lang-text');
    if (langBtnText) {
        langBtnText.textContent = (lang === 'en') ? 'العربية' : 'English';
    }
    
    // Update page title if element with data-i18n-title exists
    const pageTitleEl = document.querySelector('title[data-i18n-title]');
    if (pageTitleEl) {
        const titleKey = pageTitleEl.getAttribute('data-i18n-title');
        if (dict[titleKey]) {
            document.title = (lang === 'en') 
                ? `${dict[titleKey]} - Khalijuna Wahid Trading Est.` 
                : `${dict[titleKey]} - مؤسسة خليجنا واحد للتجارة`;
        }
    }
}

function toggleLanguage() {
    const current = getCurrentLanguage();
    const nextLang = (current === 'ar') ? 'en' : 'ar';
    localStorage.setItem('khaleejuna_lang', nextLang);
    applyTranslations(nextLang);
    
    // Dispatch custom event for any listeners
    window.dispatchEvent(new CustomEvent('languageChanged', { detail: { lang: nextLang } }));
}

// Immediately apply saved language on script load
(function() {
    const savedLang = getCurrentLanguage();
    document.documentElement.lang = savedLang;
    document.documentElement.dir = (savedLang === 'en') ? 'ltr' : 'rtl';
})();

document.addEventListener('DOMContentLoaded', () => {
    applyTranslations(getCurrentLanguage());
});

